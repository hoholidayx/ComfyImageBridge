#!/usr/bin/env python3
"""Install and control the explicitly requested monitoring/sleep system services.

The installed root controller is a root-owned standalone copy. It never imports
the user-writable SDK as root; SDK operations are always run as the configured
ComfyUI user. Ordinary stop/restart controls only the hardware monitor.
"""
import argparse
import json
import os
from pathlib import Path
import pwd
import signal
import stat
import subprocess
import sys
import tempfile
import time


PREFIX = 'myhermes2comfy'
MONITOR = PREFIX + '-monitor.service'
SLEEP = PREFIX + '-sleep.service'
RESUME = PREFIX + '-resume.service'
OWNER = PREFIX + '-resume-owner.service'
UNITS = (MONITOR, SLEEP, RESUME, OWNER)
CONFIG = Path('/etc/myhermes2comfy/service.json')
CONTROLLER = Path('/usr/local/libexec/myhermes2comfy-control.py')
UNIT_DIR = Path('/etc/systemd/system')
MARKER = '# Generated by MyHermes2Comfy hardware-service.py\n'
_PENDING_COMMANDS = []


def quoted(value):
    value = str(value)
    if any(c in value for c in '\n\r\0'):
        raise ValueError('Service paths and account names must be single-line values')
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('%', '%%') + '"'


def directory_value(value):
    # WorkingDirectory is a scalar path, unlike the word-list ExecStart parser.
    # Quotes there are literal filename characters on systemd 255.
    value = str(value)
    if not Path(value).is_absolute() or any(c in value for c in '\n\r\0'):
        raise ValueError('WorkingDirectory must be an absolute single-line path')
    return value.replace('%', '%%')


def render_units(config, controller=CONTROLLER, config_path=CONFIG):
    root, python, user, home = (config[k] for k in ('root', 'python', 'user', 'home'))
    common = (f'User={user}\nWorkingDirectory={directory_value(root)}\n'
              f'Environment={quoted("HOME=" + home)}\n'
              f'Environment={quoted("COMFY_WORKFLOW_HOME=" + root)}\n'
              f'Environment={quoted("PATH=" + config["path"])}\n'
              'StandardInput=null\nStandardOutput=journal\nStandardError=journal\n'
              'NoNewPrivileges=yes\n')
    control = f'/usr/bin/python3 {quoted(controller)} --config {quoted(config_path)} '
    module = f'{quoted(python)} -m comfy_workflow_api.'
    return {
        MONITOR: MARKER + '[Unit]\nDescription=ComfyUI CPU/GPU health and mail queue\nAfter=local-fs.target\n'
            f'RequiresMountsFor={quoted(root)}\n\n[Service]\nType=simple\n' + common +
            f'ExecStart={module}hardware_monitor --root {quoted(root)} run\n'
            'Restart=on-failure\nRestartSec=5\nTimeoutStopSec=10\nNice=10\n'
            '\n[Install]\nWantedBy=multi-user.target\n',
        SLEEP: MARKER + '[Unit]\nDescription=Release ComfyUI resources before sleep\n'
            'DefaultDependencies=no\nBefore=sleep.target\nAfter=local-fs.target\n'
            f'RequiresMountsFor={quoted(root)}\nStopWhenUnneeded=yes\n'
            '\n[Service]\nType=oneshot\nRemainAfterExit=yes\n'
            'StandardInput=null\nStandardOutput=journal\nStandardError=journal\n'
            f'ExecStart={control}coordinator-pre\nExecStop={control}coordinator-post\n'
            f'ExecStopPost={control}coordinator-cleanup\n'
            'TimeoutStartSec=180\nTimeoutStopSec=60\n'
            '\n[Install]\nRequiredBy=sleep.target\n',
        RESUME: MARKER + '[Unit]\nDescription=Verify and finish one ComfyUI sleep recovery\n'
            'After=systemd-suspend.service systemd-hibernate.service systemd-hybrid-sleep.service systemd-suspend-then-hibernate.service\n'
            f'RequiresMountsFor={quoted(root)}\n\n[Service]\nType=oneshot\n'
            'StandardInput=null\nStandardOutput=journal\nStandardError=journal\n'
            f'ExecStart={control}coordinator-resume\nTimeoutStartSec=660\nRestart=no\n',
        OWNER: MARKER + '[Unit]\nDescription=Own ComfyUI processes created during sleep recovery\n'
            f'RequiresMountsFor={quoted(root)}\n\n[Service]\nType=oneshot\nRemainAfterExit=yes\n' + common +
            f'ExecStart={module}sleep_cycle --root {quoted(root)} resume-owner\n'
            'TimeoutStartSec=600\nTimeoutStopSec=140\nRestart=no\n',
    }


def command(argv, timeout=15, check=True):
    _PENDING_COMMANDS[:] = [p for p in _PENDING_COMMANDS if p.poll() is None]
    with tempfile.TemporaryFile() as output, tempfile.TemporaryFile() as error:
        process = subprocess.Popen(argv, stdin=subprocess.DEVNULL, stdout=output,
                                   stderr=error, start_new_session=True)
        birth = Path(f'/proc/{process.pid}/stat')
        try:
            saved = birth.read_text().rsplit(')', 1)[1].split()[19]
        except (OSError, ValueError, IndexError):
            saved = None
        deadline = time.monotonic() + timeout
        while process.poll() is None and time.monotonic() < deadline:
            time.sleep(min(.05, max(0, deadline-time.monotonic())))
        if process.poll() is None:
            try:
                current = birth.read_text().rsplit(')', 1)[1].split()[19]
                if saved and current == saved and os.getpgid(process.pid) == process.pid:
                    os.killpg(process.pid, signal.SIGKILL)
            except (OSError, ValueError, IndexError):
                pass
            if process.poll() is None:
                _PENDING_COMMANDS.append(process)
            raise TimeoutError(f'{Path(argv[0]).name} exceeded {timeout} seconds; inspect service state')
        output.seek(0)
        error.seek(0)
        result = subprocess.CompletedProcess(argv, process.returncode,
            output.read(2 * 1024 * 1024).decode(errors='replace'), error.read(8192).decode(errors='replace'))
    if check and result.returncode:
        raise RuntimeError(f'{Path(argv[0]).name} failed ({result.returncode}): {result.stderr.strip()[:1000]}')
    return result


def systemctl(*args, timeout=15, check=True):
    return command(['/usr/bin/systemctl', *args], timeout, check)


def require_root():
    if sys.platform != 'linux' or os.geteuid() != 0:
        raise RuntimeError('This action needs sudo on the Ubuntu host')


def load_config(path):
    path = Path(path)
    info = path.stat()
    if info.st_uid != 0 or info.st_mode & 0o022 or path.is_symlink():
        raise RuntimeError('Controller configuration must be root-owned and not writable by group/others')
    config = json.loads(path.read_text())
    account = pwd.getpwnam(config['user'])
    if account.pw_uid == 0 or account.pw_uid != config['uid']:
        raise RuntimeError('Configured ComfyUI account changed; reinstall the service')
    if not Path(config['root']).is_absolute() or not Path(config['python']).is_absolute():
        raise RuntimeError('Configured SDK paths must be absolute')
    return config


def user_command(config, module, action=None, token=None, timeout=155, reason=None):
    if os.geteuid() not in (0, config['uid']):
        raise RuntimeError('Run this command as the configured user or sudo')
    prefix = ['/usr/sbin/runuser', '-u', config['user'], '--'] if os.geteuid() == 0 else []
    argv = [*prefix, '/usr/bin/env',
            'HOME=' + config['home'], 'COMFY_WORKFLOW_HOME=' + config['root'],
            'PATH=' + config['path'], config['python'], '-m', module,
            '--root', config['root']]
    if token:
        argv += ['--token', token]
    if reason:
        argv += ['--reason', str(reason)[:1000]]
    if action:
        argv.append(action)
    result = command(argv, timeout, check=False)
    try:
        value = json.loads(result.stdout)
    except ValueError as exc:
        raise RuntimeError(f'SDK operation returned no JSON ({result.returncode}): {result.stderr[-1000:]}') from exc
    if not isinstance(value, dict):
        raise RuntimeError('SDK operation returned an invalid result')
    return value


def cycle(config, action, token=None, timeout=155, reason=None):
    return user_command(config, 'comfy_workflow_api.sleep_cycle', action, token, timeout, reason)


def phase(value):
    return value.get('phase', value.get('state'))


def owner_state():
    result = systemctl('show', OWNER, '-p', 'ActiveState', '--value', check=False, timeout=3)
    return result.stdout.strip() or 'inactive'


def owner_ready():
    raw = systemctl('show', OWNER, '-p', 'ActiveState', '-p', 'SubState', check=False, timeout=3).stdout
    values = dict(line.split('=', 1) for line in raw.splitlines() if '=' in line)
    return values.get('ActiveState') == 'active' and values.get('SubState') == 'exited'


def owner_members():
    value = systemctl('show', OWNER, '-p', 'ControlGroup', '--value', check=False, timeout=3).stdout.strip()
    if not value:
        return []
    base = Path('/sys/fs/cgroup').resolve()
    path = (base / value.lstrip('/')).resolve()
    if base not in path.parents or path == base:
        raise RuntimeError('Unexpected owner cgroup; no process will be signalled')
    members = set()
    if path.exists():
        for item in path.rglob('cgroup.procs'):
            members.update(int(pid) for pid in item.read_text().split())
    return sorted(members)


def stop_empty_owner():
    if owner_state() in ('activating', 'deactivating'):
        raise RuntimeError('A recovery unit is still changing state; sleep refused')
    if owner_members():
        raise RuntimeError('Recovery cgroup still contains processes; refusing to stop or signal it')
    systemctl('stop', OWNER, timeout=3)
    systemctl('reset-failed', OWNER, check=False, timeout=3)


def dispatch_resume():
    systemctl('start', '--no-block', RESUME)


def verify_monitor(config, timeout_seconds=20):
    """Type=simple starting successfully does not prove Python initialized."""
    deadline = time.monotonic()+timeout_seconds
    last = {}
    while time.monotonic() < deadline:
        remaining = max(.05, deadline-time.monotonic())
        raw = systemctl('show', MONITOR, '-p', 'ActiveState', '-p', 'MainPID',
                        timeout=min(3, remaining), check=False).stdout
        unit = dict(line.split('=', 1) for line in raw.splitlines() if '=' in line)
        try:
            pid = int(unit.get('MainPID', 0))
        except ValueError:
            pid = 0
        if unit.get('ActiveState') == 'active' and pid:
            health = user_command(config, 'comfy_workflow_api.hardware_monitor', 'status',
                                  timeout=min(5, max(.05, deadline-time.monotonic())))
            last = {'unit': unit, 'running': health.get('running'), 'stale': health.get('stale')}
            if health.get('running') and not health.get('stale') and health.get('process', {}).get('pid') == pid:
                return {'unit': MONITOR, 'main_pid': pid, 'health': health}
        else:
            last = {'unit': unit}
        time.sleep(min(.25, max(0, deadline-time.monotonic())))
    raise RuntimeError('Monitor did not publish fresh health for its MainPID: '+json.dumps(last))


def coordinator(config, action):
    current = cycle(config, 'status', timeout=5)
    token = current.get('cycle_token')
    if action == 'coordinator-pre':
        prepared = False
        try:
            recovery = systemctl('show', RESUME, '-p', 'ActiveState', '--value', check=False, timeout=3).stdout.strip()
            if recovery in ('activating', 'deactivating'):
                raise RuntimeError('Previous recovery coordinator is still finishing; sleep refused')
            result = cycle(config, 'pre')
            if not result.get('success') or phase(result) != 'sleeping':
                raise RuntimeError(result.get('error') or result.get('message') or 'Sleep preparation refused')
            token = result['cycle_token']
            prepared = True
            stop_empty_owner()
            return result
        except Exception:
            if prepared:
                cleanup = cycle(config, 'abort', token=token, timeout=10)
                if cleanup.get('needs_restore'):
                    dispatch_resume()
            raise
    if action in ('coordinator-post', 'coordinator-cleanup'):
        # ExecStopPost also runs after a failed ExecStart; only abort that path.
        if action == 'coordinator-cleanup':
            if os.environ.get('SERVICE_RESULT', 'success') == 'success':
                return {'success': True, 'state': 'no_cleanup_needed'}
            if phase(current) not in ('preparing', 'sleeping'):
                return {'success': True, 'state': 'no_cleanup_needed'}
            result = cycle(config, 'abort', token=token, timeout=10)
            if result.get('needs_restore'):
                dispatch_resume()
            return result
        if current.get('active') and phase(current) in ('sleeping', 'restoring', 'restored'):
            dispatch_resume()
        return {'success': True, 'state': 'recovery_dispatched', 'cycle_token': token}
    if action == 'coordinator-resume':
        if not current.get('active') or phase(current) not in ('sleeping', 'restoring', 'restored') or not token:
            return {'success': False, 'state': phase(current), 'message': 'No pending recovery; no automatic retry'}
        try:
            if current.get('was_running') and phase(current) != 'restored':
                if owner_state() != 'inactive':
                    raise RuntimeError('Unexpected existing owner unit; no duplicate recovery was started')
                systemctl('start', OWNER, timeout=615)
            if current.get('was_running') and not owner_ready():
                raise RuntimeError('Recovery owner did not finish activation')
            result = cycle(config, 'finalize', token=token, timeout=15)
            if not result.get('success'):
                raise RuntimeError(result.get('error') or result.get('message') or 'Recovery verification failed; gate remains closed')
            return result
        except Exception as exc:
            cycle(config, 'fail', token=token, reason=str(exc), timeout=10)
            raise
    raise ValueError('Unknown coordinator operation')


def atomic_write(path, content, mode):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix='.' + path.name + '-', dir=path.parent)
    try:
        with os.fdopen(fd, 'wb' if isinstance(content, bytes) else 'w') as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def installation_config(root, user):
    root = Path(root).expanduser().resolve()
    account = pwd.getpwnam(user)
    if account.pw_uid == 0:
        raise ValueError('Run ComfyUI as a regular user, not root')
    python = root / '.venv/bin/python'
    if not python.is_file() or not (root / 'src/comfy_workflow_api/sleep_cycle.py').is_file():
        raise ValueError('Deploy the complete Ubuntu package and run uv sync --locked first')
    return {'schema_version': 1, 'root': str(root), 'python': str(python),
            'user': user, 'uid': account.pw_uid, 'home': account.pw_dir,
            'path': str(Path(account.pw_dir)/'.local/bin') + ':/usr/local/bin:/usr/bin:/bin'}


def validate_units(units):
    # Validate before replacing any live configuration. The temporary basenames
    # match the installed units, so systemd still resolves their dependencies.
    with tempfile.TemporaryDirectory(prefix=PREFIX + '-units-') as directory:
        paths = []
        for name, content in units.items():
            path = Path(directory)/name
            path.write_text(content)
            paths.append(str(path))
        command(['/usr/bin/systemd-analyze', 'verify', *paths], timeout=30)


def enabled_state(name):
    value = systemctl('is-enabled', name, check=False).stdout.strip()
    if value not in ('enabled', 'enabled-runtime', 'disabled', 'static', 'indirect', 'not-found'):
        raise RuntimeError(f'Unexpected enablement state for {name}: {value!r}; installation refused')
    return value


def service_snapshot():
    files = {path: (path.read_bytes(), stat.S_IMODE(path.stat().st_mode)) if path.exists() else None
             for path in (CONFIG, CONTROLLER, *(UNIT_DIR/name for name in UNITS))}
    enabled = {name: enabled_state(name) for name in (SLEEP, MONITOR)}
    monitor_state = systemctl('show', MONITOR, '-p', 'ActiveState', '--value', check=False).stdout.strip()
    if monitor_state not in ('active', 'inactive', 'failed'):
        raise RuntimeError('Monitor state is changing or unknown; operation refused')
    return files, enabled, monitor_state == 'active'


def check_unit_ownership():
    for name in UNITS:
        path = UNIT_DIR/name
        if path.is_symlink() or (path.exists() and not path.read_text().startswith(MARKER)):
            raise RuntimeError(f'{name} is not managed by this installer; refusing operation')
    if CONTROLLER.is_symlink():
        raise RuntimeError('Controller must be a regular managed file; refusing operation')


def rollback_services(files, enabled, enablement_touched, monitor_touched, monitor_was_running, old_config):
    errors = []
    def attempt(label, operation):
        try:
            operation()
        except Exception as exc:
            errors.append(label + ': ' + str(exc))
    if monitor_touched:
        attempt('stop replacement monitor', lambda: systemctl('stop', MONITOR, timeout=20))
    if enablement_touched:
        attempt('remove replacement enablement', lambda: systemctl('disable', SLEEP, MONITOR))
    for path, saved in files.items():
        if saved is None:
            attempt('remove ' + str(path), lambda path=path: path.unlink(missing_ok=True))
        else:
            content, mode = saved
            attempt('restore ' + str(path), lambda path=path, content=content, mode=mode:
                    atomic_write(path, content, mode))
    attempt('reload previous units', lambda: systemctl('daemon-reload'))
    for name, state in enabled.items():
        if enablement_touched and state in ('enabled', 'enabled-runtime'):
            options = ['--runtime'] if state == 'enabled-runtime' else []
            attempt('restore enablement for ' + name,
                    lambda name=name, options=options: systemctl('enable', *options, name))
    if monitor_touched and monitor_was_running:
        attempt('start previous monitor', lambda: systemctl('start', MONITOR, timeout=20))
        attempt('verify previous monitor', lambda: verify_monitor(old_config))
    return errors


def install(config, dry_run=False):
    units = render_units(config)
    if dry_run:
        return {'success': True, 'config': config, 'units': units}
    require_root()
    old = config
    if CONFIG.exists():
        old = load_config(CONFIG)
        if (old['root'], old['user']) != (config['root'], config['user']):
            raise RuntimeError('Another deployment owns these service names; uninstall it first')
        if cycle(old, 'status', timeout=10).get('active'):
            raise RuntimeError('A sleep cycle is active; installation refused')
    check_unit_ownership()
    validate_units(units)
    files, enabled, monitor_was_running = service_snapshot()
    monitor_touched = False
    enablement_touched = False
    try:
        atomic_write(CONFIG, json.dumps(config, indent=2) + '\n', 0o644)
        atomic_write(CONTROLLER, Path(__file__).read_text(), 0o755)
        for name, content in units.items():
            atomic_write(UNIT_DIR/name, content, 0o644)
        systemctl('daemon-reload')
        enablement_touched = True
        systemctl('enable', SLEEP, MONITOR)
        # enable --now is a no-op for an already active service. An upgrade must
        # replace its process before accepting fresh health from the new code.
        monitor_touched = True
        systemctl('restart', MONITOR, timeout=20)
        verified = verify_monitor(config)
    except BaseException as exc:
        errors = rollback_services(files, enabled, enablement_touched, monitor_touched, monitor_was_running, old)
        message = 'Installation failed; previous service files and enablement restored: ' + (str(exc) or type(exc).__name__)
        if errors:
            message = 'Installation failed; rollback needs attention: ' + (str(exc) or type(exc).__name__) + '; ' + '; '.join(errors)
        raise RuntimeError(message) from exc
    return {'success': True, 'config_path': str(CONFIG), 'controller': str(CONTROLLER),
            'units': list(UNITS), 'monitor': verified}


def uninstall(config):
    require_root()
    if cycle(config, 'status', timeout=10).get('active'):
        raise RuntimeError('Finish or abort the pending sleep cycle before uninstalling')
    if owner_members():
        raise RuntimeError('Stop ComfyUI with its manager when idle before uninstalling its recovery owner')
    check_unit_ownership()
    files, enabled, monitor_was_running = service_snapshot()
    # Complete all ownership checks before changing monitor or sleep enablement.
    # This may stop only an empty owner; rollback never starts the owner again.
    stop_empty_owner()
    monitor_touched = False
    try:
        systemctl('disable', SLEEP)
        monitor_touched = True
        systemctl('disable', '--now', MONITOR)
        for name in UNITS:
            (UNIT_DIR/name).unlink(missing_ok=True)
        CONFIG.unlink(missing_ok=True)
        CONTROLLER.unlink(missing_ok=True)
        systemctl('daemon-reload')
    except BaseException as exc:
        errors = rollback_services(files, enabled, True, monitor_touched, monitor_was_running, config)
        message = 'Uninstall failed; previous service files and enablement restored: ' + (str(exc) or type(exc).__name__)
        if errors:
            message = 'Uninstall failed; rollback needs attention: ' + (str(exc) or type(exc).__name__) + '; ' + '; '.join(errors)
        raise RuntimeError(message) from exc
    return {'success': True, 'state': 'uninstalled', 'data_preserved': True}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--user', default=os.environ.get('SUDO_USER') or pwd.getpwuid(os.getuid()).pw_name)
    parser.add_argument('--config', type=Path, default=CONFIG)
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('action', choices=['install', 'uninstall', 'start', 'stop', 'restart', 'status', 'retry', 'abort',
        'coordinator-pre', 'coordinator-post', 'coordinator-cleanup', 'coordinator-resume'])
    args = parser.parse_args()
    try:
        if args.action == 'install':
            result = install(installation_config(args.root, args.user), args.dry_run)
        elif args.action == 'status':
            # Read only: does not require sudo, create state or touch the GPU.
            result = {'success': True, 'units': {name: systemctl('show', name, '-p', 'LoadState', '-p', 'ActiveState',
                '-p', 'SubState', '-p', 'MainPID', check=False).stdout.strip() for name in UNITS}}
            if args.config.exists():
                config = load_config(args.config)
                result['root'] = config['root']
                result['installed'] = True
            else:
                result['installed'] = False
                config = installation_config(args.root, args.user)
            result['hardware_health'] = user_command(config, 'comfy_workflow_api.hardware_monitor', 'status', timeout=10)
            result['sleep_cycle'] = cycle(config, 'status', timeout=10)
        else:
            require_root()
            config = load_config(args.config)
            if args.action == 'uninstall':
                result = uninstall(config)
            elif args.action in ('start', 'stop', 'restart'):
                systemctl(args.action, MONITOR)
                result = {'success': True, 'unit': MONITOR, 'action': args.action}
                if args.action != 'stop':
                    result['monitor'] = verify_monitor(config)
            elif args.action in ('retry', 'abort'):
                prior = cycle(config, 'status', timeout=10)
                token = prior.get('cycle_token')
                result = cycle(config, args.action, token=token, timeout=155)
                if result.get('success') and (args.action == 'retry' or result.get('needs_restore')):
                    try:
                        if args.action == 'retry':
                            stop_empty_owner()
                        systemctl('reset-failed', RESUME, check=False)
                        dispatch_resume()
                    except Exception as exc:
                        cycle(config, 'fail', token=token, reason=str(exc), timeout=10)
                        raise
            else:
                result = coordinator(config, args.action)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0 if result.get('success', True) else 1
    except Exception as exc:
        print(json.dumps({'success': False, 'error': str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
